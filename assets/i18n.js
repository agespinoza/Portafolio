export function getLanguage(value) {
  return LANGUAGES.includes(value) ? value : "en";
}

export function languageFromSearch(search) {
  return getLanguage(new URLSearchParams(search).get("lang"));
}

export function localeFor(language) {
  return LOCALES[getLanguage(language)];
}

export function t(language, key, fallback, values = {}) {
  const lang = getLanguage(language);
  const value = key.split(".").reduce((current, part) => current && current[part], MESSAGES[lang]);
  const text = value === undefined ? fallback : value;
  if (typeof text !== "string") return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`
  ));
}

export function projectText(language, id, field, fallback) {
  return t(language, `projects.${id}.${field}`, fallback);
}

export function timelineText(language, index, field, fallback) {
  return t(language, `timeline.${index}.${field}`, fallback);
}

export function dayText(language, slug, field, fallback) {
  return t(language, `labDays.${slug}.${field}`, fallback);
}

export function calendarWeekdays(language) {
  const localized = t(language, "calendar.weekdays", null);
  return Array.isArray(localized) ? localized : ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
}
